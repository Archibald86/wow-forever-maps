const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const types=require('../creature-types.js'),npcs=require('../npcs.js'),settings=require('../settings.js'),{normalizeLevel}=require('../app-core.js');
const data=JSON.parse(fs.readFileSync(path.join(__dirname,'../npc-atlas.json')));
const humanoid=data.npcs[6],beast=data.npcs[30],unknown=data.npcs[251451];
assert(types.matches(humanoid.creature,'Humanoid'));assert(!types.matches(humanoid.creature,'Beast'));
assert(types.matches(unknown.creature,'unknown'));assert(!types.matches(beast.creature,'unknown'));
assert(!types.matches({...unknown.creature,family:'Spider'},'Beast'));
assert(npcs.matches(humanoid,{npcType:'Humanoid',npcQuery:'6'}));
assert(!npcs.matches(humanoid,{npcType:'Beast',npcQuery:'6'}));
assert(!npcs.matches(humanoid,{npcType:'Humanoid',npcRole:'vendors'}));
assert.match(types.description(beast.creature),/Classic.*Forever не подтверждено/);
assert.match(types.description(JSON.parse(fs.readFileSync(path.join(__dirname,'../database/npcs.json'))).rows.find(row=>row.id===10776).creature),/Имя отличается/);
for(const value of ['__proto__','constructor','verified',null,123])assert.equal(types.validFilter(value),false);
const fixture={maps:[{id:'swampofsorrows_c60'}]},resolve=(query,saved={})=>settings.resolve(fixture,new URLSearchParams(query),saved,normalizeLevel);
assert.equal(resolve('npcType=Undead',{npcType:'Beast'}).npcType,'Undead');
assert.equal(resolve('npcType=invalid',{npcType:'Beast'}).npcType,'Beast');
assert.equal(resolve('npcType=__proto__').npcType,'all');
const state=resolve('npcType=unknown&npcs=1');assert.equal(resolve(new URL(settings.toUrl('https://test/atlas.html',state)).search).npcType,'unknown');
for(const creature of [{...beast.creature,status:'forever_verified'},{...beast.creature,type:null},{...beast.creature,source:null},{...beast.creature,type:'Spider'}])assert.throws(()=>types.validate(creature));
console.log('PASS creature types: explicit unknowns, source status, independent role/family, combined filters and URL validation');
